"""מחזור האירוע — התנאי היחיד שמפריד בין "מה קורה עכשיו" ל"מה כבר היה".

אירוע שנדחה מקבל **מחזור חדש** (``Event.cycle_number``). ההודעות של המחזור
הקודם נשארות ב-DB במלואן, אבל אינן חלק מהתמונה שהזוג רואה: אחרי דחייה, מוזמן
שקיבל הזמנה למועד הישן צריך להיספר כ"טרם קיבל הזמנה" — אחרת לא תישלח אליו
ההזמנה החדשה, והוא פשוט לא יידע שהאירוע זז.

**הכלל:** כל שאילתה שסופרת או מציגה הודעות **עבור הזוג** מסננת דרך
``current_only``. שאילתה שנוגעת בכל ההיסטוריה (מחיקת אירוע, חקירה) לא מסננת —
ובמכוון.

למה מודול נפרד וזעיר: הפילטר הזה נדרש בשמונה מקומות בקוד (הזמנות, תור ההודעות,
מסלול אישורי-ההגעה, יומן ההודעות, תמונת המצב, ה-Call Center). קבוע אחד במקום
אחד מונע את המצב שבו מקום אחד שוכח לסנן — ואז מחזור חדש נולד "מלוכלך".
המודול לא מייבא דבר מלבד המודלים, כדי שכל אחד מהם יוכל לייבא אותו בלי מעגלים.
"""
from __future__ import annotations

from typing import Optional

from sqlalchemy import or_

from app import models


def of(event: Optional[models.Event]) -> int:
    """מספר המחזור של האירוע. חסר/ישן => 1 (האירוע המקורי)."""
    if event is None:
        return 1
    return event.cycle_number or 1


def current_only(event: Optional[models.Event]):
    """תנאי SQLAlchemy: רק הודעות של המחזור הנוכחי של האירוע.

    במחזור 1 מקבלים גם שורות עם ``NULL`` — רשת ביטחון לכל DB שבו העמודה
    נוספה בלי למלא ערך לשורות קיימות. במחזורים מתקדמים יותר ``NULL`` הוא
    בהכרח נתון ישן, ולכן אינו נכלל.
    """
    number = of(event)
    if number == 1:
        return or_(
            models.Message.cycle_number == 1,
            models.Message.cycle_number.is_(None),
        )
    return models.Message.cycle_number == number
