def entries_for(event_type: str | None) -> list[dict]:
    """בוחר איזו ספרייה להגיש לפי סוג האירוע.

    חתונה (וכל אירוע ללא סוג) → עולם החתונה העשיר (``LIBRARY``, 75 תבניות).
    כל שאר 7 הסוגים הנתמכים (חינה/בר-בת-מצווה/ברית/עסקי/משפחתי/אחר) →
    ספרייה ייעודית בטון שלהם (לא רק שינוי מילה בתבנית משותפת — תוכן שנכתב
    במיוחד לסוג). ``GENERIC_LIBRARY`` נשארת רק כ-fallback ל-event_type לא
    מוכר (ערך שלא הוגדר ב-``EventType``). הוספת סוג עם ספרייה עשירה משלו =
    ספרייה חדשה + שורה חדשה ב-``_LIBRARY_BY_TYPE`` בלבד.
    """
    return _LIBRARY_BY_TYPE.get(event_type or "wedding", GENERIC_LIBRARY)


# סדר עדיפויות לבחירת סגנון ברירת המחדל לסוגים לא-חתונתיים. מפורש בכוונה —
# לא להסתמך על סדר ההופעה במערך, כדי ששינוי סדר עריכה בספרייה לא ישנה בשקט
# איזו הודעה כל אירוע חדש מקבל.
DEFAULT_STYLE_PRIORITY = ("formal", "elegant", "family")

# ``stage`` הוא גס מדי כדי לבחור לפיו לבד: לשלב ``before_event`` שייכות גם
# הודעות "יום האירוע", גם "ניווט" וגם "חנייה". בלי הסינון הזה, אירוע חינה
# היה מקבל כתבנית "לפני האירוע" דווקא את הודעת החנייה (הסגנון היחיד שהתאים
# לסדר העדיפויות). הקטגוריה מצמצמת קודם לסוג ההודעה הנכון, והסגנון בוחר בתוכו.
STAGE_PREFERRED_CATEGORY: dict[str, str] = {
    "invitation": CAT_INVITATION,
    "first_reminder": CAT_REMINDER,
    "second_reminder": CAT_REMINDER,
    "thank_you": CAT_THANK_YOU,
    "before_event": CAT_EVENT_DAY,
}


def default_body_for(event_type: str | None, stage: str) -> str | None:
    """גוף הודעת ברירת המחדל של סוג אירוע בשלב מסוים, או ``None`` אם אין.

    זהו מקור-האמת היחיד ל"מה הנוסח ההתחלתי שאירוע מהסוג הזה מקבל" — משמש גם
    את ``messaging.default_template_for`` (מסלול השליחה הישיר) וגם את
    ``rsvp_track.provision_rsvp_track`` (המסלול שמזין את עורך ההודעות). לפני
    כן כל אחד מהם החזיק לוגיקה משלו, ולכן אירוע שאינו חתונה קיבל בעורך נוסח
    חתונתי ("אנחנו [שמות בני הזוג]") גם אחרי שמסלול השליחה כבר תוקן.

    ``wedding`` מוחזר כ-``None`` בכוונה: לחתונה נשמר הנוסח ההיסטורי של
    הקורא (``DEFAULT_TEMPLATE`` / ``VeyaTemplate.body``), כדי שלא ישתנה כלום
    לאירועים הקיימים.

    ``stage`` הוא שלב ה-``VeyaTemplate`` (invitation / first_reminder /
    second_reminder / thank_you / before_event). הבחירה בתוך השלב היא
    *קטגוריה מועדפת → סגנון לפי עדיפות → הראשונה הזמינה*. אין התאמה לשלב →
    ``None``, והקורא נשאר עם הנוסח שלו.
    """
    if not event_type or event_type == "wedding":
        return None

    entries = [e for e in entries_for(event_type) if e.get("stage") == stage]
    if not entries:
        return None

    # מצמצמים לקטגוריה המועדפת של השלב, אם יש בה משהו (אחרת נשארים עם הכול).
    preferred = STAGE_PREFERRED_CATEGORY.get(stage)
    in_category = [e for e in entries if e.get("category") == preferred]
    candidates = in_category or entries

    for style in DEFAULT_STYLE_PRIORITY:
        for entry in candidates:
            if entry.get("style") == style:
                return entry["body"]
    return candidates[0]["body"]
